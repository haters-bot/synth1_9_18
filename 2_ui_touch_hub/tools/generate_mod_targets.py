"""Generate the shared modulation target geometry; IDs follow params.vh."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
TARGETS=[(0x01,200,22),(0x02,260,22),(0x03,320,22),(0x04,380,22),(0x05,1182,22)]
for offset,x0 in [(0,0),(0x10,416)]:
    TARGETS += [(p+offset,x+x0,y) for p,x,y in [
        (0x13,64,268),(0x14,134,268),(0x15,204,268),(0x16,274,268),(0x1b,344,268),
        (0x17,84,326),(0x18,164,326),(0x19,264,326),(0x1a,344,326)]]
TARGETS += [(0x30+i,x,y) for i,x,y in [(0,950,268),(1,1040,268),(2,1130,268),(3,950,326),(4,1040,326),(5,1130,326)]]
TARGETS += [(0x40+i,64+66*i,652) for i in range(5)]
TARGETS += [(0x60+i,448+i*56 if i<6 else 444+(i-6)*48 if i<13 else 448+(i-13)*56,
             416 if i<6 else 524 if i<13 else 632) for i in range(19)]
if __name__=='__main__':
    for i,(_,x,y) in enumerate(TARGETS):
        for _,other_x,other_y in TARGETS[i+1:]:
            assert abs(x-other_x)>44 or abs(y-other_y)>44, 'Binding hitboxes must be disjoint'
    lines=['// Generated by tools/generate_mod_targets.py; include inside a module.']
    for name,bits,col in [('mod_id',8,0),('mod_cx',14,1),('mod_cy',14,2)]:
        lines += [f'function [{bits-1}:0] {name};','    input integer idx;','    begin case(idx)']
        lines += [f"        {i}: {name}={bits}'d{row[col]};" for i,row in enumerate(TARGETS)]
        lines += [f'        default:{name}=0;','    endcase end','endfunction']
    lines += ['function [5:0] mod_target;','    input [13:0] px,py;','    integer k;',
        '    reg [5:0] selected;','    reg any_hit;',
        "    begin selected=0;any_hit=0;",'        for(k=0;k<53;k=k+1) begin',
        '            if(px>=mod_cx(k)-22 && px<=mod_cx(k)+22 &&',
        '               py>=mod_cy(k)-22 && py<=mod_cy(k)+22) begin',
        '                selected=selected | k[5:0];any_hit=1;',
        '            end','        end',"        mod_target=any_hit ? selected : 6'd63;",
        '    end','endfunction']
    (ROOT/'rtl/ui_vector_engine/mod_targets.vh').write_text('\n'.join(lines)+'\n')
