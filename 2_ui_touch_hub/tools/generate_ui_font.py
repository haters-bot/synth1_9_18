"""Reproduce native 7x10 coverage glyphs from Pillow 12.2's bundled Aileron.

Source font metadata: Sora Sagano, 'No Rights Reserved.' No network download.
Existing character IDs and eight-pixel character advances are preserved.
"""
from datetime import datetime
from hashlib import sha256
import json
from pathlib import Path
import re

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
CHARS = ' ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-+:.'
LEVELS = (0, 64, 192, 255)


def main():
    font = ImageFont.load_default(size=104)
    font_hash = sha256(font.path.getvalue()).hexdigest()
    cap = font.getbbox('H')
    glyphs = []
    for char in CHARS:
        box = font.getbbox(char)
        # Common cap top / baseline; punctuation keeps its vertical position.
        raw = Image.new('L', (max(1, box[2]-box[0])+8, cap[3]-cap[1]), 0)
        ImageDraw.Draw(raw).text((4-box[0], -cap[1]), char, font=font, fill=255)
        bounds = raw.getbbox()
        if bounds:
            raw = raw.crop((bounds[0], 0, bounds[2], raw.height))
        width = min(7, max(1, round(raw.width * 10 / raw.height)))
        small = raw.resize((width, 10), Image.Resampling.LANCZOS)
        canvas = Image.new('L', (7, 10))
        canvas.paste(small, ((7-width)//2, 0))
        glyphs.append([[0 if canvas.getpixel((x,y))<32 else
                        1 if canvas.getpixel((x,y))<112 else
                        2 if canvas.getpixel((x,y))<208 else 3
                        for x in range(7)] for y in range(10)])

    data = {'font': 'Pillow 12.2 Aileron Regular', 'font_sha256': font_hash,
            'author': 'Sora Sagano', 'rights': 'No Rights Reserved.',
            'characters': CHARS, 'coverage_levels': list(LEVELS), 'glyphs': glyphs}
    (ROOT/'tools/ui_font_7x10.json').write_text(json.dumps(data, indent=2)+'\n', encoding='utf-8')
    lines = ['// Generated by tools/generate_ui_font.py. Sora Sagano / Aileron.',
             '// Source metadata: No Rights Reserved. Native 7x10, 8px advance.',
             '// Coverage codes 0/1/2/3 mean 0, 1/4, 3/4, 1.',
             '`ifndef FONT_7X10_VH', '`define FONT_7X10_VH',
             'function [13:0] get_font_7x10_row;',
             '    input [5:0] ch;', '    input [3:0] ry;', '    begin',
             '        case ({ch,ry})']
    for i, rows in enumerate(glyphs):
        for y, row in enumerate(rows):
            bits = ''.join(f'{a:02b}' for a in row)
            if int(bits, 2):
                lines.append(f"            10'd{i*16+y}: get_font_7x10_row=14'b{bits};")
    lines += ["            default: get_font_7x10_row=14'd0;", '        endcase',
              '    end', 'endfunction',
              'function [1:0] get_font_7x10;', '    input [5:0] ch;',
              '    input [2:0] rx;', '    input [3:0] ry;',
              '    reg [13:0] row_bits;', '    begin',
              '        row_bits=get_font_7x10_row(ch,ry);', '        case(rx)']
    for x in range(7):
        lines.append(f'            {x}: get_font_7x10=row_bits[{13-x*2}:{12-x*2}];')
    lines += ["            default: get_font_7x10=2'd0;", '        endcase',
              '    end', 'endfunction',
              '// Used only on literal strings: fold ASCII conversion at elaboration.',
              'function [143:0] pack_font24;', '    input [191:0] text;',
              '    integer i;', '    reg [7:0] c;', '    begin',
              '        pack_font24=0;', '        for(i=0;i<24;i=i+1) begin',
              '            c=text[191-i*8 -: 8];',
              '            if(c>=65 && c<=90) pack_font24[143-i*6 -: 6]=c-64;',
              '            else if(c>=48 && c<=57) pack_font24[143-i*6 -: 6]=c-21;',
              '            else if(c==45) pack_font24[143-i*6 -: 6]=37;',
              '            else if(c==43) pack_font24[143-i*6 -: 6]=38;',
              '            else if(c==58) pack_font24[143-i*6 -: 6]=39;',
              '            else if(c==46) pack_font24[143-i*6 -: 6]=40;',
              '        end', '    end', 'endfunction', '`endif', '']
    (ROOT/'rtl/ui_vector_engine/font_7x10.vh').write_text('\n'.join(lines), encoding='utf-8')

    out = ROOT/'impl'/('font_preview_'+datetime.now().strftime('%Y%m%d_%H%M%S'))
    out.mkdir(exist_ok=False)
    old = (ROOT/'rtl/ui_vector_engine/font_3x5.vh').read_text()
    names = ['SPACE']+list('ABCDEFGHIJKLMNOPQRSTUVWXYZ')+list('0123456789')+['MINUS','PLUS','COLON','DOT']
    sheet = Image.new('RGB',(760,240),'#101720')
    draw = ImageDraw.Draw(sheet)
    draw.text((12,8),'R15H: 3x5 enlarged 2x     /     R15I: native 7x10 coverage', fill='white')
    for i, (name, rows) in enumerate(zip(names, glyphs)):
        x=12+(i%20)*37; y=40+(i//20)*64
        match = re.search(r'`CH_'+name+r':\s+bitmap\s*=\s*15\x27b([01_]+)',old)
        bits = match.group(1).replace('_','') if match else '0'*15
        for yy in range(10):
            for xx in range(7):
                if xx<6 and bits[(yy//2)*3+xx//2]=='1':
                    draw.point((x+xx,y+yy), fill='white')
                a=LEVELS[rows[yy][xx]]
                bg=(16,23,32)
                draw.point((x+12+xx,y+yy), fill=tuple((255*a+b*(255-a))//255 for b in bg))
        draw.text((x,y+16), CHARS[i], fill='#a0b8cc')
    sheet.save(out/'contact.png')
    sheet.resize((1520,480),Image.Resampling.NEAREST).save(out/'contact_2x.png')
    print(out, flush=True)


if __name__ == '__main__':
    main()
