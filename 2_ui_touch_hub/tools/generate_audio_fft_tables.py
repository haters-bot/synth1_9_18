"""Generate synchronous 1024-point Hann/window and Q1.15 FFT twiddle ROMs."""
from pathlib import Path
import math

ROOT = Path(__file__).resolve().parents[1]


def main():
    out = ['// Generated by tools/generate_audio_fft_tables.py.\n',
           'module audio_fft_tables(input wire clk, input wire [9:0] window_address,\n',
           ' input wire [8:0] twiddle_address, output reg signed [15:0] window_value,\n',
           ' output reg signed [15:0] twiddle_real,twiddle_imag);\n',
           'reg signed [15:0] hann[0:1023],wr[0:511],wi[0:511];\ninitial begin\n']
    tables = [('hann', [round(32767 * .5 * (1-math.cos(2*math.pi*n/1024))) for n in range(1024)]),
              ('wr', [round(32767*math.cos(2*math.pi*n/1024)) for n in range(512)]),
              ('wi', [round(-32767*math.sin(2*math.pi*n/1024)) for n in range(512)])]
    for name, values in tables:
        out += [f"{name}[{n}]=16'h{v & 65535:04X};\n" for n, v in enumerate(values)]
    out += ['end\nalways @(posedge clk) begin\n',
            ' window_value<=hann[window_address];\n',
            ' twiddle_real<=wr[twiddle_address];twiddle_imag<=wi[twiddle_address];\n',
            'end\nendmodule\n']
    path = ROOT/'rtl/audio/audio_fft_tables.v'
    path.write_text(''.join(out), encoding='ascii')
    print(path)


if __name__ == '__main__':
    main()
