"""Generate the UI-only extension IDs; CC numbers checked against audio dbffe37.

These are static controls, never additional/reordered LFO modulation targets.
"""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
# name, wire CC, reset, maximum. Booleans use 0/127 (audio tests nonzero).
CONTROLS=[
 ('OSCA_WARP_MODE',38,0,11),('OSCB_WARP_MODE',40,0,11),
 ('OSCA_WT_INDEX',49,0,15),('OSCB_WT_INDEX',50,0,15),
 ('EFFECT_MODE',51,0,3),('DIST_ENABLE',58,0,127),('DIST_TYPE',59,0,2),
 ('DIST_DRIVE',60,32,127),('DIST_TONE',61,127,127),('DIST_MIX',62,64,127),
 ('CHORUS_ENABLE',63,0,127),('CHORUS_RATE',64,20,127),('CHORUS_DEPTH',65,32,127),
 ('CHORUS_DELAY',66,48,127),('CHORUS_FEEDBACK',67,20,127),('CHORUS_MIX',68,64,127),
 ('PHASER_ENABLE',69,0,127),('PHASER_RATE',70,20,127),('PHASER_DEPTH',71,48,127),
 ('PHASER_CENTER',72,64,127),('PHASER_FEEDBACK',73,20,127),('PHASER_MIX',74,64,127),
 ('COMP_ENABLE',75,0,127),('COMP_THRESH',76,96,127),('COMP_RATIO',77,64,127),
 ('COMP_ATTACK',78,20,127),('COMP_RELEASE',79,80,127),('COMP_MAKEUP',80,0,127),('COMP_MIX',81,127,127),
 ('VIB_ENABLE',82,0,127),('VIB_RATE',83,52,127),('VIB_DEPTH',84,0,127),
 ('PORTA_ENABLE',85,0,127),('PORTA_TIME',86,80,127),
]
assert len(CONTROLS)==34

def generate():
    out=['// Generated by tools/generate_audio_controls.py; include inside a module.',
         '// A0..C1 are UI INTERNAL IDs. They are not audio SysEx IDs.']
    for name,width,field,default in [('audio_extra_cc',7,1,0),('audio_extra_default',7,2,0),('audio_extra_max',7,3,127)]:
        out += [f'function [{width-1}:0] {name};',' input integer index;',' begin case(index)']
        out += [f"  {i}: {name}="+("`UI_WAVETABLE_COUNT-1" if name=='audio_extra_max' and i in (2,3) else f"7'd{v[field]}")+f"; // {v[0]}" for i,v in enumerate(CONTROLS)]
        out += [f"  default: {name}=7'd{default};",' endcase end','endfunction']
    out += ['function [7:0] audio_fx_cell_id;',' input [2:0] page; input integer cell;',' begin audio_fx_cell_id=0; case(page)']
    pages=[[0xa7,0xa8,0xa9],[0xb1,0xb2,0xb3,0xb4,0xb5],[0xab,0xac,0xad,0xae,0xaf],
           [0x61,0x60,0x65,0x66,0x67,0x6c],[0xb7,0xb8,0xb9,0xba,0xbb,0xbc],
           [0xbe,0xc1,0xbf]] # PITCH: vibrato rate/depth left, glide time right.
    for p,ids in enumerate(pages):
        out += [f' {p}: case(cell)']+[f"  {i}: audio_fx_cell_id=8'h{v:02X};" for i,v in enumerate(ids)]+['  default: audio_fx_cell_id=0; endcase']
    out += [' default: audio_fx_cell_id=0; endcase end','endfunction',
            'function [13:0] audio_cell_x; input integer cell; begin audio_cell_x=cell%2==0 ? 432 : 608; end endfunction',
            'function [13:0] audio_cell_y; input integer cell; begin audio_cell_y=450+(cell/2)*44; end endfunction']
    import re
    (ROOT/'rtl/ui_vector_engine/audio_extra_controls.vh').write_text('`include "wavetable_catalog.vh"\n'+re.sub(r'\bcell\b','cell_index','\n'.join(out))+'\n')
    macros='\n'.join(f"`define PARAM_ID_{v[0]:<20} 8'h{0xa0+i:02X} // CC{v[1]}" for i,v in enumerate(CONTROLS))+'\n'
    params=ROOT/'rtl/ui_vector_engine/params.vh'
    text=params.read_text(encoding='utf-8')
    start='// BEGIN AUDIO EXTENSION IDS\n';end='// END AUDIO EXTENSION IDS\n'
    if start in text:text=text[:text.index(start)]+start+macros+end+text[text.index(end)+len(end):]
    else:text=text.replace('// 3. Panel Bounding Boxes',start+macros+end+'\n// 3. Panel Bounding Boxes')
    params.write_text(text,encoding='utf-8')

if __name__=='__main__':generate()
